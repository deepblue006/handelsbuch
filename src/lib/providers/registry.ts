export function getProvider(id: string): ProviderInfo {
  const p = PROVIDERS.find((x) => x.id === id);
  if (!p) throw new Error(`Unbekannter Provider: ${id}`);
  return p;
}

/** Konfigurationsstatus: fehlen benötigte Umgebungsvariablen? (Werte selbst werden nie ausgegeben.) */
export function configStatus(p: ProviderInfo, env: Record<string, string | undefined> = process.env) {
  const missing = p.envKeys.filter((k) => !env[k]);
  const optionalKey = p.id === "defillama";
  return {
    configured: optionalKey || missing.length === 0,
    missingEnv: optionalKey ? [] : missing,
  };
}
